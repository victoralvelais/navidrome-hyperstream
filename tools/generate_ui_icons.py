"""Bundle only Hyperstream's UI symbols from pinned, attributed icon packs.

Edit ui_icons.csv to add or remap a symbol, then run this script. Downloads are
build-time only; the app never contacts an icon CDN. No third-party Dart runtime
or remote icon code is embedded.
"""

import argparse
import csv
import hashlib
import json
from pathlib import Path
import urllib.request

ROOT = Path(__file__).resolve().parents[1]
CLIENT = ROOT / 'apps/client'
STYLES = {
    'iconoir': ('iconoir', ''),
    'phosphorLight': ('ph', ''),
    'lucide': ('lucide', ''),
    'solarLinear': ('solar', '-linear'),
    'solarOutline': ('solar', '-outline'),
    'solarBroken': ('solar', '-broken'),
    'solarLineDuotone': ('solar', '-line-duotone'),
    'solarBold': ('solar', '-bold'),
    'solarBoldDuotone': ('solar', '-bold-duotone'),
}


def resolve(pack, name):
    if name in pack['icons']:
        return pack['icons'][name]
    alias = pack['aliases'][name]
    result = {**resolve(pack, alias['parent']), **alias}
    # All currently used aliases are naming aliases; reject geometric aliases
    # until their transforms are implemented instead of silently misdrawing.
    if any(result.get(key) for key in ['rotate', 'hFlip', 'vFlip']):
        raise ValueError(f'Use the original drawing for transformed alias {name}')
    return result


def generate(cache):
    sources = json.loads((ROOT/'tools/ui_icons_sources.json').read_text())
    packs = {}
    cache.mkdir(parents=True, exist_ok=True)
    for name, source in sources.items():
        cached = cache / (name + '.json')
        raw = cached.read_bytes() if cached.exists() else b''
        if hashlib.sha256(raw).hexdigest() != source['sha256']:
            with urllib.request.urlopen(source['url'], timeout=45) as response:
                raw = response.read()
            if hashlib.sha256(raw).hexdigest() != source['sha256']:
                raise ValueError(f'Icon source checksum mismatch: {name}')
            cached.write_bytes(raw)
        packs[name] = json.loads(raw)

    with (ROOT/'tools/ui_icons.csv').open(encoding='utf-8', newline='') as file:
        rows = [{k:v.strip() for k,v in row.items()} for row in csv.DictReader(file)]
    output = [
        '// Generated by tools/generate_ui_icons.py from tools/ui_icons.csv.',
        '// Edit the CSV rather than this file. Artwork credits: assets/licenses/.',
        "part of 'app_icon.dart';", '',
        'final _iconBindings = <IconData, _IconBinding>{',
    ]
    count = 0
    for row in rows:
        cupertino = 'CupertinoIcons.'+row['cupertino'] if row['cupertino'] else 'null'
        for symbol in row['material'].split():
            output.append(f"  Icons.{symbol}: const _IconBinding('{row['name']}', {cupertino}),")
        for style, (pack_name, suffix) in STYLES.items():
            pack = packs[pack_name]
            name = row[pack_name]+suffix
            icon = resolve(pack, name)
            width = icon.get('width', pack.get('width', 24))
            height = icon.get('height', pack.get('height', 24))
            body = icon['body']
            # Runtime tint uses the alpha channel, preserving Solar's two tones.
            body = body.replace('currentColor', '#000000')
            # Keep solid transport and active states legible in Lucide as well.
            if row['name'] == 'record' or (pack_name == 'lucide' and row['name'] in {
                'play', 'pause', 'skip_next', 'skip_previous',
                'heart_fill', 'star_fill', 'record',
            }):
                body = body.replace('fill="none"', 'fill="#000000"')
            svg = f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 {width} {height}">{body}</svg>\n'
            path = CLIENT / f"assets/icons/{style}/{row['name']}.svg"
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(svg, encoding='utf-8', newline='\n')
            count += 1
    output.extend(['};', ''])
    (CLIENT/'lib/widgets/app_icon_data.dart').write_text('\n'.join(output), encoding='utf-8', newline='\n')
    print(f'Generated {count} SVG assets for {len(rows)} actions across {len(STYLES)} styles, plus Cupertino mappings.')


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--cache-dir', type=Path, default=ROOT/'.tools/ui-icons')
    generate(parser.parse_args().cache_dir)
